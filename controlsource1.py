presentase = float(input("Masukkan presentase : "))

if presentase >= 90:
    print("Performa sangat baik")
elif presentase >= 80:
    print("Performa sangat bagus")
elif presentase >= 70:
    print("Performa bagus")
elif presentase >= 60:
    print("Performa rata-rata")
else :
    print("Performa kurang")
